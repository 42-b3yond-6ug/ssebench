#!/usr/bin/env python3
"""Generate datasets/pilot/THIRD_PARTY.md.

The upstream repository, pinned commit, fix commits and PoC files come from each
task's sse/config.yaml and Dockerfile. License findings, advisories, reports and
PoC provenance come from datasets/pilot/third_party.json, which caches what was
looked up in the upstream repositories so that this script runs offline.

    python3 tools/dataset/third_party.py            rewrite THIRD_PARTY.md
    python3 tools/dataset/third_party.py --check    exit 1 if it is out of date

Both modes fail when third_party.json no longer matches the tasks, for example
when a Dockerfile pins a different commit than the one whose license was checked.
"""

from __future__ import annotations

import argparse
import difflib
import json
import re
import sys
from collections import Counter, defaultdict
from dataclasses import dataclass
from pathlib import Path
from typing import Any

DATASET = Path(__file__).resolve().parents[2] / "datasets" / "pilot"

KNOWN_SPDX = {
    "Apache-2.0",
    "BSD-2-Clause",
    "BSD-3-Clause",
    "GPL-2.0-or-later",
    "MIT",
    "PHP-3.01",
    "Python-2.0",
    "Vim",
    "libtiff",
}
LANGUAGES = {"c": "C", "go": "Go", "rust": "Rust"}
ADVISORY_RE = re.compile(r"\b(CVE-\d{4}-\d{4,}|GHSA(?:-[0-9a-z]{4}){3}|GO-\d{4}-\d{4,}|RUSTSEC-\d{4}-\d{4})\b")
ADVISORY_URLS = {
    "CVE": "https://nvd.nist.gov/vuln/detail/{}",
    "GHSA": "https://github.com/advisories/{}",
    "GO": "https://pkg.go.dev/vuln/{}",
    "RUSTSEC": "https://rustsec.org/advisories/{}.html",
}
POC_KINDS = {
    "report": "reproducer from the public report",
    "derived": "reproducer derived from the public report",
    "written": "written for SSEBench from the public report",
}
SHA_RE = re.compile(r"[0-9a-f]{40}")
CLONE_RE = re.compile(r"\bgit clone\s+(\S+)")
CHECKOUT_RE = re.compile(r"\bgit checkout\s+(\S+)")
COPY_SRC_RE = re.compile(r"^COPY\s+\./([^\s/]+)/?\s+/src/", re.MULTILINE)

INTRO = """\
# Third-party material in the pilot dataset

<!-- Generated by tools/dataset/third_party.py from the task configs, the
     Dockerfiles and third_party.json. Edit those and re-run the script. -->

This file lists, for each of the {total} tasks in the pilot dataset of SSEBench
({counts}), the upstream project it is built from, that project's license, the
upstream fix, the public advisories, the public report, and where the
proof-of-concept (PoC) inputs come from.

## How the dataset is licensed

- Material written for SSEBench is licensed under [CC BY 4.0](LICENSE): task
  configs, scripts, Dockerfiles, harnesses, and the reports and PoCs that were
  written for SSEBench.
- Upstream source code is not part of this repository, except for the vendored
  crates listed below. Each task's Dockerfile clones the upstream repository at
  a pinned commit when the image is built. Upstream code, and the distribution
  packages, Go modules and crates that the build pulls in, keep their own
  licenses.
- Every task ships the upstream fix and test diffs (`sse/diffs/`). They are
  derived from the upstream project and keep the license listed for the task,
  not CC BY 4.0.
- Reports in `sse/reports/` either quote the public report linked for the task
  or were written for SSEBench. Quoted text remains the work of its authors.
- PoC inputs taken from upstream test suites keep the upstream license; inputs
  taken from public reports remain the work of their reporters. Each task says
  where its PoC comes from.

Licenses are SPDX expressions determined at the pinned commit, or for vendored
crates at the vendored version, from the upstream license files and package
metadata.
"""

TAKEDOWN = """\
## Takedown and contact

If you hold rights in material listed here and believe it is attributed
incorrectly, used beyond what its license allows, or should be removed, please
[open an issue](https://github.com/42-b3yond-6ug/ssebench/issues/new) naming the
task and the files concerned. We will correct the attribution or remove the
material.

For security-sensitive matters, such as a PoC for a problem that is not yet
fixed or disclosed upstream, do not open a public issue. Use
[private vulnerability reporting](https://github.com/42-b3yond-6ug/ssebench/security/advisories/new)
instead, as described in [SECURITY.md](../../SECURITY.md).
"""


class DataError(Exception):
    pass


# The task configs use a small block-style subset of YAML (nested mappings,
# sequences of scalars, optionally quoted scalars). Parsing that subset here keeps
# the script dependency-free; anything outside it is rejected, not guessed at.
def parse_config(text: str, where: str) -> dict[str, Any]:
    lines: list[tuple[int, str]] = []
    for raw in text.splitlines():
        if raw.strip() and not raw.lstrip().startswith("#"):
            lines.append((len(raw) - len(raw.lstrip(" ")), raw.strip()))
    if not lines:
        raise DataError(f"{where}: empty config")
    try:
        value, i = _block(lines, 0, lines[0][0])
    except DataError as exc:
        raise DataError(f"{where}: {exc}") from None
    if i != len(lines) or not isinstance(value, dict):
        near = lines[min(i, len(lines) - 1)][1]
        raise DataError(f"{where}: unsupported YAML near {near!r}")
    return value


def _is_item(content: str) -> bool:
    return content == "-" or content.startswith("- ")


def _scalar(text: str) -> str | None:
    text = text.strip()
    if len(text) >= 2 and text[0] == text[-1] and text[0] in "\"'":
        return text[1:-1] or None
    if text[:1] in ("[", "{", "|", ">", "&", "*", "!") or " #" in text:
        raise DataError(f"unsupported YAML value {text!r}")
    return text or None


def _block(lines: list[tuple[int, str]], i: int, indent: int) -> tuple[Any, int]:
    if _is_item(lines[i][1]):
        items: list[str | None] = []
        while i < len(lines) and lines[i][0] == indent and _is_item(lines[i][1]):
            items.append(_scalar(lines[i][1][1:]))
            i += 1
        return items, i
    mapping: dict[str, Any] = {}
    while i < len(lines) and lines[i][0] == indent and not _is_item(lines[i][1]):
        key, sep, rest = lines[i][1].partition(":")
        if not sep:
            break
        i += 1
        nested = i < len(lines) and (lines[i][0] > indent or (lines[i][0] == indent and _is_item(lines[i][1])))
        if rest.strip():
            mapping[key.strip()] = _scalar(rest)
        elif nested:
            mapping[key.strip()], i = _block(lines, i, lines[i][0])
        else:
            mapping[key.strip()] = None
    return mapping, i


@dataclass
class Task:
    name: str
    language: str
    upstream: str
    license: str
    source: str
    fixes: list[str]
    advisories: list[str]
    report: str
    pocs: list[dict[str, Any]]
    vendored: dict[str, Any] | None


def spdx_ids(expression: str) -> set[str]:
    bare = expression.replace("(", "").replace(")", "")
    return set(re.split(r"\s+(?:AND|OR)\s+", bare))


def cargo_field(cargo_toml: str, key: str) -> str | None:
    package = re.search(r"^\[package\]\s*$(.*?)(?=^\[|\Z)", cargo_toml, re.MULTILINE | re.DOTALL)
    body = package.group(1) if package else ""
    match = re.search(rf'^{key}\s*=\s*"([^"]*)"', body, re.MULTILINE)
    return match.group(1) if match else None


def cargo_license(value: str) -> str:
    # Older crates write dual licensing as "MIT/Apache-2.0"; SPDX spells it with OR.
    return " OR ".join(part.strip() for part in value.split("/"))


def advisory_key(advisory: str) -> tuple[int, str]:
    return list(ADVISORY_URLS).index(advisory.split("-", 1)[0]), advisory


def advisory_link(advisory: str, overrides: dict[str, str]) -> str:
    default = ADVISORY_URLS[advisory.split("-", 1)[0]].format(advisory)
    return f"[{advisory}]({overrides.get(advisory, default)})"


def commit_link(repo: str, sha: str) -> str:
    if repo.startswith("https://github.com/"):
        return f"[`{sha[:12]}`]({repo}/commit/{sha})"
    return f"[`{sha[:12]}`]({repo}/-/commit/{sha})"


def check_vendored(name: str, task_dir: Path, dockerfile: str, vendored: dict[str, Any], license_: str) -> list[str]:
    errors: list[str] = []
    crate_dir = task_dir / vendored["dir"]
    if vendored["dir"] not in COPY_SRC_RE.findall(dockerfile):
        errors.append(f"{name}: Dockerfile does not copy ./{vendored['dir']} to /src")
    cargo_path = crate_dir / "Cargo.toml"
    cargo = cargo_path.read_text() if cargo_path.is_file() else ""
    for key in ("name", "version"):
        found = cargo_field(cargo, key)
        if found != vendored[key]:
            errors.append(f"{name}: crate {key} is {found!r}, not {vendored[key]!r}")
    declared = cargo_field(cargo, "license")
    if declared is None or cargo_license(declared) != license_:
        errors.append(f"{name}: crate declares {declared!r}, not {license_!r}")
    for license_file in vendored["license_files"]:
        if not (crate_dir / license_file).is_file():
            errors.append(f"{name}: {vendored['dir']}/{license_file} is missing")
    return errors


def load(dataset: Path) -> tuple[list[Task], dict[str, Any], list[str]]:
    data: dict[str, Any] = json.loads((dataset / "third_party.json").read_text())
    upstreams: dict[str, Any] = data["upstreams"]
    entries: dict[str, Any] = data["tasks"]
    # Repository advisories that never reached the global GitHub database 404 at
    # the default URL, so they are linked where they were published.
    advisory_urls: dict[str, str] = data.get("advisory_urls", {})
    errors: list[str] = []
    tasks: list[Task] = []

    task_dirs = sorted(p.parent.parent for p in dataset.glob("*/sse/config.yaml"))
    names = {d.name for d in task_dirs}
    for name in sorted(set(entries) - names):
        errors.append(f"{name}: listed in third_party.json but not a task")
    for upstream, meta in sorted(upstreams.items()):
        unknown = spdx_ids(meta["license"]) - KNOWN_SPDX
        if unknown:
            errors.append(f"{upstream}: unknown SPDX id(s) {sorted(unknown)}")

    for task_dir in task_dirs:
        name = task_dir.name
        entry: dict[str, Any] | None = entries.get(name)
        if entry is None:
            errors.append(f"{name}: missing from third_party.json")
            continue
        try:
            config_path = task_dir / "sse" / "config.yaml"
            config = parse_config(config_path.read_text(), f"{name}/sse/config.yaml")
        except DataError as exc:
            errors.append(str(exc))
            continue
        dockerfile = (task_dir / "Dockerfile").read_text()
        upstream: str = entry.get("upstream", "")
        info: dict[str, Any] | None = upstreams.get(upstream)
        if info is None:
            errors.append(f"{name}: upstream {upstream!r} is not under upstreams")
            continue

        clones = [url.removesuffix(".git") for url in CLONE_RE.findall(dockerfile)]
        pins = CHECKOUT_RE.findall(dockerfile)
        vendored: dict[str, Any] | None = entry.get("vendored")
        pinned: str | None = None
        if clones:
            if len(clones) != 1 or len(pins) != 1 or not SHA_RE.fullmatch(pins[0]):
                errors.append(f"{name}: need one git clone and one full-SHA checkout")
                continue
            if clones[0] != upstream:
                errors.append(f"{name}: Dockerfile clones {clones[0]}, not {upstream}")
            pinned = pin = pins[0]
            if entry.get("license_checked_at") != pin:
                errors.append(
                    f"{name}: Dockerfile pins {pin}, but the license was checked"
                    f" at {entry.get('license_checked_at')}; re-check it"
                )
            source = f"commit {commit_link(upstream, pin)}, cloned by the Dockerfile"
        elif vendored:
            errors += check_vendored(name, task_dir, dockerfile, vendored, info["license"])
            source = (
                f"vendored in `{vendored['dir']}/`: {vendored['name']}"
                f" {vendored['version']}, upstream commit"
                f" {commit_link(upstream, vendored['revision'])}"
            )
        else:
            errors.append(f"{name}: Dockerfile clones nothing and nothing is vendored")
            continue

        fixes: list[str] = entry.get("fix_commits") or [
            c.strip() for c in str(config.get("patch_commit") or "").split(",")
        ]
        if not all(SHA_RE.fullmatch(c) for c in fixes):
            errors.append(f"{name}: fix commits {fixes!r} are not full SHAs")
        elif pinned in fixes:
            errors.append(f"{name}: fix commit equals the pinned commit")

        advisories = sorted(entry.get("advisories", []), key=advisory_key)
        references = " ".join(r for r in config.get("reference") or [] if r)
        missing = sorted(set(ADVISORY_RE.findall(references)) - set(advisories))
        if missing:
            errors.append(f"{name}: config cites advisories {missing} not listed")
        links = [advisory_link(a, advisory_urls) for a in advisories]

        pocs: list[dict[str, Any]] = entry.get("pocs", [])
        covered = {f for poc in pocs for f in poc["files"]}
        files = config.get("files") or {}
        configured = {f"sse/{p}" for p in files.get("poc") or []}
        for path in sorted(configured - covered):
            errors.append(f"{name}: PoC {path} has no provenance entry")
        for path in sorted(covered):
            if not (task_dir / path).is_file():
                errors.append(f"{name}: {path} does not exist")
        for poc in pocs:
            if poc.get("kind") not in POC_KINDS and not poc.get("text"):
                errors.append(f"{name}: PoC entry {poc['files']} has no kind or text")

        language = str(config.get("language") or "")
        if language not in LANGUAGES:
            errors.append(f"{name}: unknown language {language!r}")
        if not entry.get("report"):
            errors.append(f"{name}: no report link")

        tasks.append(
            Task(
                name=name,
                language=language,
                upstream=upstream,
                license=info["license"],
                source=source,
                fixes=fixes,
                advisories=links,
                report=entry.get("report", ""),
                pocs=pocs,
                vendored=vendored,
            )
        )

    used = {t.upstream for t in tasks}
    for upstream in sorted(set(upstreams) - used):
        errors.append(f"{upstream}: listed under upstreams but used by no task")
    cited = {a for entry in entries.values() for a in entry.get("advisories", [])}
    for advisory in sorted(set(advisory_urls) - cited):
        errors.append(f"{advisory}: has a URL override but no task cites it")
    return tasks, upstreams, errors


def render_poc(poc: dict[str, Any], report: str) -> str:
    files = ", ".join(f"`{f}`" for f in poc["files"])
    if poc.get("text"):
        return f"{files}: {poc['text']}"
    return f"{files}: {POC_KINDS[poc['kind']]} <{report}>."


def render_task(task: Task, upstreams: dict[str, Any]) -> list[str]:
    info = upstreams[task.upstream]
    evidence = ", ".join(f"`{f}`" for f in info["license_files"])
    fixes = ", ".join(commit_link(task.upstream, c) for c in task.fixes)
    advisories = ", ".join(task.advisories)
    lines = [
        "",
        f"#### {task.name}",
        "",
        f"- Upstream: [{info['name']}]({task.upstream})",
        f"- License: `{task.license}` (from {evidence})",
        f"- Source: {task.source}",
        f"- Fix: {fixes}",
        f"- Advisories: {advisories or 'none known'}",
        f"- Report: <{task.report}>",
    ]
    pocs = [render_poc(poc, task.report) for poc in task.pocs]
    if len(pocs) == 1:
        lines.append(f"- PoC: {pocs[0]}")
    else:
        lines.append("- PoC:")
        lines += [f"  - {poc}" for poc in pocs]
    return lines


def render(tasks: list[Task], upstreams: dict[str, Any]) -> str:
    per_language = Counter(task.language for task in tasks)
    counts = ", ".join(f"{per_language[code]} {label}" for code, label in LANGUAGES.items() if per_language[code])
    out = INTRO.format(total=len(tasks), counts=counts).splitlines()

    by_license: dict[str, list[Task]] = defaultdict(list)
    by_upstream: dict[str, list[Task]] = defaultdict(list)
    for task in tasks:
        by_license[task.license].append(task)
        by_upstream[task.upstream].append(task)

    out += [
        "",
        "## License summary",
        "",
        "| License | Tasks | Upstream projects |",
        "|---|---:|---|",
    ]
    for license_, group in sorted(by_license.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        projects = sorted({upstreams[t.upstream]["name"] for t in group}, key=str.lower)
        out.append(f"| `{license_}` | {len(group)} | {', '.join(projects)} |")

    out += ["", "## Copyleft and other special terms", ""]
    noted = [(u, i) for u, i in upstreams.items() if i.get("note")]
    for upstream, info in sorted(noted, key=lambda kv: kv[1]["name"].lower()):
        n = len(by_upstream[upstream])
        scope = f"`{info['license']}`, {n} task{'s' if n != 1 else ''}"
        out.append(f"- **{info['name']}** ({scope}): {info['note']}")

    out += [
        "",
        "## Vendored crates",
        "",
        "These tasks include the upstream crate source in the task directory instead",
        "of cloning it. The crate's own license files are kept next to its source.",
        "",
        "| Task | Directory | Crate | License | License files |",
        "|---|---|---|---|---|",
    ]
    notes: list[str] = []
    for task in tasks:
        v = task.vendored
        if v is None:
            continue
        files = ", ".join(f"`{f}`" for f in v["license_files"])
        crate = f"{v['name']} {v['version']}"
        out.append(f"| `{task.name}` | `{v['dir']}/` | {crate} | `{task.license}` | {files} |")
        if v.get("note"):
            notes.append(f"- `{task.name}`: {v['note']}")
    if notes:
        out += ["", *notes]

    out += ["", "## Tasks"]
    for code, label in LANGUAGES.items():
        group = sorted((t for t in tasks if t.language == code), key=lambda t: t.name.lower())
        if group:
            out += ["", f"### {label}"]
            for task in group:
                out += render_task(task, upstreams)

    out += ["", *TAKEDOWN.splitlines()]
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate THIRD_PARTY.md.")
    _ = parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 instead of writing when THIRD_PARTY.md is out of date",
    )
    _ = parser.add_argument(
        "--dataset",
        type=Path,
        default=DATASET,
        help="dataset directory (default: %(default)s)",
    )
    args = parser.parse_args()
    dataset: Path = args.dataset
    check: bool = args.check

    tasks, upstreams, errors = load(dataset)
    if errors:
        print("\n".join(f"error: {e}" for e in errors), file=sys.stderr)
        return 1
    text = render(tasks, upstreams)
    target = dataset / "THIRD_PARTY.md"
    current = target.read_text() if target.exists() else ""
    if current == text:
        return 0
    if check:
        diff = difflib.unified_diff(
            current.splitlines(),
            text.splitlines(),
            str(target),
            "generated",
            lineterm="",
        )
        print("\n".join(list(diff)[:60]), file=sys.stderr)
        print(f"error: {target} is out of date; run {__file__}", file=sys.stderr)
        return 1
    _ = target.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
